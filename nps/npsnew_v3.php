function gradeNo($g){return (int)str_replace('Grade_','',$g);}
function nextStage($slots,$value){
    foreach($slots as $i=>$v){
        if((int)$v===(int)$value)return isset($slots[$i+1])?(float)$slots[$i+1]:(float)$v;
    }
    return (float)end($slots);
}
function equalOrNext($slots,$target){
    foreach($slots as $v)if($v>=$target)return (float)$v;
    return (float)end($slots);
}
