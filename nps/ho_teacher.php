function loadBasic(g,selected=''){
    basic.innerHTML='<option value="">-- Choose Basic --</option>';
    if(!g||!nps2015[g]){
        basic.disabled=true;
        submit.disabled=true;
        return;
    }
    nps2015[g].forEach(v=>{
        let o=document.createElement('option');
        o.value=v;
        o.textContent='BDT '+Number(v).toLocaleString('en-US');
        if(String(v)===String(selected))o.selected=true;
        basic.appendChild(o);
    });
    basic.disabled=false;
    submit.disabled=!basic.value;
}

function toggleAdminGrade(){
    if(isTeacher.checked){
        adminGradeGroup.classList.add('show');
        adminGrade.required = true;
    } else {
        adminGradeGroup.classList.remove('show');
        adminGrade.required = false;
    }
}

grade.addEventListener('change',()=>loadBasic(grade.value));
basic.addEventListener('change',()=>submit.disabled=!basic.value);
isTeacher.addEventListener('change',toggleAdminGrade);

if(postedGrade)loadBasic(postedGrade,postedBasic);
if(postedIsTeacher){ isTeacher.checked = true; }
toggleAdminGrade();

