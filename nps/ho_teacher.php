function gradeNo($g){return (int)str_replace('Grade_','',$g);}
function nextStage($slots,$value){
    foreach($slots as $i=>$v){
        if((int)$v===(int)$value)return isset($slots[$i+1])?(float)$slots[$i+1]:(float)$v;
    }
    return (float)end($slots);
}
function equalOrNext($slots,$target){
    foreach($slots as $v)if($v>=$target)return (float)$v;
    return (float)end($slots);
}
function percent1($grade){return gradeNo($grade)<=9?40:50;}
function percent2($grade){return gradeNo($grade)<=9?70:75;}

// Helper: get next stage of current basic in 2015 scale; return null if last stage
function getNextStage2015($slots, $currentBasic) {
    foreach($slots as $i => $v) {
        if((float)$v === (float)$currentBasic) {
            return isset($slots[$i+1]) ? (float)$slots[$i+1] : null;
        }
    }
    return null;
}

// Benefit % derived from grade: 1–9 → 10%, 10–20 → 15%
function benefitPercentByGrade($grade){
    return gradeNo($grade) <= 9 ? 10 : 15;
}

// House rent calculator based on city and basic slab (with floor minimums)
// City: 'dhaka' or 'other'
function houseRentAmount($city, $basic){
    $basic = (float)$basic;

    if ($city === 'dhaka') {
        if ($basic <= 9700) {
            $rate = 0.65; $min = 5600;
        } elseif ($basic <= 16000) {
            $rate = 0.60; $min = 6400;
        } elseif ($basic <= 35500) {
            $rate = 0.55; $min = 9600;
        } else {
            $rate = 0.50; $min = 19500;
        }
    } else { // other city
        if ($basic <= 9700) {
            $rate = 0.50; $min = 4500;
        } elseif ($basic <= 16000) {
            $rate = 0.45; $min = 4800;
        } elseif ($basic <= 35500) {
            $rate = 0.40; $min = 7000;
        } else {
            $rate = 0.35; $min = 13800;
        }
    }

    $amount = $basic * $rate;
    if ($amount < $min) $amount = $min;
    return $amount;
}

